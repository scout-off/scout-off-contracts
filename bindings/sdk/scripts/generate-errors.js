#!/usr/bin/env node
//
// Generates bindings/sdk/src/errors.ts from contracts/*/src/errors.rs.
//
// Usage:
//   node scripts/generate-errors.js          -- write src/errors.ts
//   node scripts/generate-errors.js --check  -- exit 1 if the file has drifted
//
// CI drift check: run with --check after every change to contracts/*/src/errors.rs.
//
"use strict";
const fs = require("fs");
const path = require("path");

const REPO_ROOT = path.resolve(__dirname, "../../..");
const CONTRACTS = [
  ["Progress", "progress", "ProgressError"],
  ["Registration", "registration", "ScoutChainError"],
  ["ScoutAccess", "scout_access", "ScoutAccessError"],
  ["Verification", "verification", "VerificationError"],
];
const OUT = path.join(__dirname, "../src/errors.ts");

function parseErrors(rsPath) {
  const src = fs.readFileSync(rsPath, "utf8");
  const m = src.match(/pub enum \w+Error \{([\s\S]*?)\n\}/);
  if (!m) throw new Error(`no enum found in ${rsPath}`);
  const variants = new Map();
  for (const line of m[1].split("\n")) {
    const vm = line.trim().match(/^([A-Z][A-Za-z0-9]+)\s*=\s*(\d+)\s*,?$/);
    if (vm) variants.set(vm[1], Number(vm[2]));
  }
  return variants;
}

function emit() {
  let out = `/**
 * Typed contract error classes for @scoutchain/sdk.
 *
 * AUTO-GENERATED by scripts/generate-errors.js — do not edit by hand.
 * Run \`npm run generate-errors\` from bindings/sdk to regenerate.
 * Run \`npm run check-errors-drift\` in CI to verify this file is up to date.
 *
 * Source: contracts/{progress,registration,scout_access,verification}/src/errors.rs
 */

/** Base class for all ScoutChain contract errors. */
export class ScoutChainContractError extends Error {
  constructor(
    public readonly code: number,
    public readonly variant: string,
    public readonly contract: string,
  ) {
    super(\`\${contract} error \${code}: \${variant}\`);
    this.name = \`\${contract}Error\`;
    Object.setPrototypeOf(this, new.target.prototype);
  }
}
`;

  for (const [name, dir, rustEnum] of CONTRACTS) {
    const rsPath = path.join(REPO_ROOT, "contracts", dir, "src", "errors.rs");
    const variants = parseErrors(rsPath);
    if (variants.size === 0) {
      throw new Error(`no variants parsed from ${rsPath}`);
    }
    const className = `${name}ContractError`;
    const nsName = `${name}Error`;

    out += `
// ─── ${name} contract errors (${variants.size} variants) ────────────

export class ${className} extends ScoutChainContractError {
  constructor(code: number, variant: string) {
    super(code, variant, "${name}");
    this.name = "${className}";
    Object.setPrototypeOf(this, new.target.prototype);
  }
}

export namespace ${nsName} {
`;
    let consts = "";
    let map = "";
    for (const [variant, code] of [...variants.entries()].sort((a, b) => a[1] - b[1])) {
      consts += `  export const ${variant} = ${code};\n`;
      map += `    ${code}: "${variant}",\n`;
    }
    out += consts;
    out += `
  const _codeToName: Record<number, string> = {
${map}  };

  export function fromCode(code: number): ${className} {
    return new ${className}(code, _codeToName[code] ?? \`Unknown(\${code})\`);
  }
}
`;
  }

  return out;
}

function main() {
  const generated = emit();
  if (process.argv.includes("--check")) {
    const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (existing !== generated) {
      console.error(
        "ERROR: bindings/sdk/src/errors.ts is out of date with contracts/*/src/errors.rs.\n" +
          "Run `npm run generate-errors` from bindings/sdk and commit the result."
      );
      process.exit(1);
    }
    console.log("OK: bindings/sdk/src/errors.ts is in sync with Rust sources.");
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, generated);
    console.log(`Wrote ${OUT}`);
  }
}

main();
